"""Generate aperture.yaml: hourly feeds + 30-day passes/bundles + public free paths.

    python gen_aperture.py                     # aperture.base.yaml + pricing.yaml -> aperture.yaml
    python gen_aperture.py --check             # exit 1 if aperture.yaml is out of date
    python gen_aperture.py --out ~/.aperture/aperture.yaml --gateway-secret-file gateway.secret
    python gen_aperture.py ... --listenaddr 0.0.0.0:443 --tls   # production (HTTPS, see deploy/README.md)

Inputs
------
--base     aperture.base.yaml: global settings and every hourly rule definition are
           kept; only feeds that pricing.yaml `access:` lists as paid are sold (lnd settings are moved under `authenticator:`,
           where Aperture actually reads them).
--pricing  pricing.yaml `plans:` -> one Aperture service per plan.
BTC/USD    needed to turn USD plan prices into sats (static bundle prices and
           the pass fallback used when the BTC feed is down). Fetched from the
           pricer's feeds unless --btc-usd is given.

Generated services
------------------
* one service per plan (path ^/api/v1/<prefix>/<feed>$, its own timeout)
* `public-free`: auth off for the free routes only (samples, quotes, /buy,
  discovery). The operator dashboard and /api/proxy/* are deliberately NOT
  routed: Aperture cannot reach them, so they stay private.

Gateway secret
--------------
With --gateway-secret-file, every paid service gets
`headers: {X-AurAgrid-Gateway: <secret>}`. Aperture overwrites any value a
client sends, and the backend (AURAGRID_GATEWAY_SECRET) refuses paid routes
without it, so the backend cannot be used to skip the paywall even if its
port is exposed. The output then contains a secret: do not commit it.
"""
import argparse
import difflib
import os
import re
import stat
import sys

import yaml

from pass_support import feed_path, load_access, load_plans
from pricer import aggregate, fetch_all, round_sig

GATEWAY_HEADER = "X-AurAgrid-Gateway"
PUBLIC_SERVICE = "public-free"
FREE_FEEDS_SERVICE = "free-feeds"
RETIRED_SERVICE = "retired"
PUBLIC_PATHS = (
    r"^/(buy|terms|llms\.txt|robots\.txt|status|status\.json|openapi\.json|agent-manifest\.json"
    r"|\.well-known/ai-plugin\.json|\.well-known/l402-services"
    r"|api/v1/sample/[a-z0-9-]+|api/v1/price/[a-z0-9/-]+)$"
)
PUBLIC_RATE = {"requests": 60, "per": "1m", "burst": 20}   # per client IP; protects egress
BATCH_PREFIX = os.environ.get("AURAGRID_BATCH_PREFIX", "batch")
LND_KEYS = ("lndhost", "tlspath", "macdir", "network")
HEADER = "# Generated by gen_aperture.py from aperture.base.yaml + pricing.yaml. Edit those, then rerun.\n"


def usd_to_sats(usd: float, btc_usd: float) -> int:
    return round_sig(max(1, round(usd / btc_usd * 100_000_000)))


def normalize_settings(base: dict) -> dict:
    """Global settings minus services, with lnd settings under `authenticator:`."""
    settings = {k: v for k, v in base.items() if k != "services"}
    auth = dict(settings.get("authenticator") or {})
    for key in LND_KEYS:
        if key in settings:
            auth.setdefault(key, settings.pop(key))
    auth.setdefault("network", "mainnet")
    settings["authenticator"] = auth
    return settings


def _matches_any(svc: dict, paths) -> bool:
    try:
        rx = re.compile(svc.get("pathregexp") or "")
    except re.error:
        return False
    return any(rx.match(p) for p in paths)


def build(base: dict, plans: list, btc_usd, gateway_secret=None, access=None) -> dict:
    generated = {PUBLIC_SERVICE, FREE_FEEDS_SERVICE, RETIRED_SERVICE} | {p.name for p in plans}
    hourly = [dict(s) for s in base.get("services") or [] if s.get("name") not in generated]
    if access is not None:
        # Only sell feeds listed as paid: the others have no data source (or are free).
        paid_paths = [feed_path(k, BATCH_PREFIX) for k in access.paid]
        hourly = [s for s in hourly if _matches_any(s, paid_paths)]
    template = hourly[0] if hourly else {"hostregexp": ".*", "address": "127.0.0.1:8000", "protocol": "http"}
    common = {k: template[k] for k in ("hostregexp", "address", "protocol") if k in template}
    pricer_cfg = next((s["dynamicprice"] for s in hourly if (s.get("dynamicprice") or {}).get("enabled")),
                      {"enabled": True, "grpcaddress": "127.0.0.1:10010", "insecure": True})

    plan_services = []
    for plan in plans:
        if plan.sats is not None:
            sats = plan.sats
        elif btc_usd:
            sats = usd_to_sats(plan.usd, btc_usd)
        else:
            raise SystemExit("plan %s: no BTC/USD price to convert $%.2f (pass --btc-usd or set sats)"
                             % (plan.name, plan.usd))
        svc = {"name": plan.name, **common, "pathregexp": plan.pathregexp,
               "price": sats,            # static price; the pricer's fallback for USD-pegged passes
               "timeout": plan.timeout}  # integer seconds (Aperture's Timeout is int64)
        if plan.dynamic:
            svc["dynamicprice"] = dict(pricer_cfg)
        plan_services.append(svc)

    public = {"name": PUBLIC_SERVICE, **common, "pathregexp": PUBLIC_PATHS,
              "auth": "off", "authwhitelistpaths": [PUBLIC_PATHS], "price": 0,
              "ratelimits": [{"pathregexp": PUBLIC_PATHS, **PUBLIC_RATE}]}
    free = []
    if access is not None and access.free:
        rx = "^(%s)$" % "|".join(re.escape(feed_path(k, BATCH_PREFIX)) for k in sorted(access.free))
        free = [{"name": FREE_FEEDS_SERVICE, **common, "pathregexp": rx, "auth": "off",
                 "authwhitelistpaths": [rx], "price": 0,
                 "ratelimits": [{"pathregexp": rx, "requests": access.requests_per_minute, "per": "1m",
                                 "burst": access.burst}]}]

    retired = []
    if access is not None and (access.retired or access.retired_prefixes):
        parts = [re.escape(feed_path(k, BATCH_PREFIX)) for k in sorted(access.retired)]
        parts += [re.escape("/api/v1/%s/" % p) + ".*" for p in sorted(access.retired_prefixes)]
        rx = "^(%s)$" % "|".join(parts)
        retired = [{"name": RETIRED_SERVICE, **common, "pathregexp": rx, "auth": "off",
                    "authwhitelistpaths": [rx], "price": 0,
                    "ratelimits": [{"pathregexp": rx, **PUBLIC_RATE}]}]

    paid = plan_services + hourly
    if gateway_secret:
        for svc in paid:
            svc["headers"] = {**(svc.get("headers") or {}), GATEWAY_HEADER: gateway_secret}
    return {**normalize_settings(base), "services": free + retired + paid + [public]}


def validate(config: dict, plans: list, access=None) -> list:
    """Problems that would make Aperture misroute or mis-sell a plan or feed."""
    problems, compiled = [], []
    for svc in config["services"]:
        try:
            compiled.append((svc, re.compile(svc["pathregexp"])))
        except (KeyError, re.error) as exc:
            problems.append("service %s: bad pathregexp (%s)" % (svc.get("name"), exc))
        if not isinstance(svc.get("timeout", 0), int):
            problems.append("service %s: timeout must be an integer number of seconds" % svc.get("name"))
    for plan in plans:
        for path in plan.paths():
            first = next((s for s, rx in compiled if rx.match(path)), None)   # Aperture: first match wins
            if first is None or first["name"] != plan.name:
                problems.append("%s is served by %s, not plan %s"
                                % (path, first and first["name"], plan.name))
    if access is not None:
        for key in access.paid:
            path = feed_path(key, BATCH_PREFIX)
            first = next((s for s, rx in compiled if rx.match(path)), None)
            if first is None or first["name"] in (FREE_FEEDS_SERVICE, PUBLIC_SERVICE, RETIRED_SERVICE):
                problems.append("paid feed %s (%s) has no paid Aperture rule in the base config" % (key, path))
        for key in access.free:
            path = feed_path(key, BATCH_PREFIX)
            first = next((s for s, rx in compiled if rx.match(path)), None)
            if first is None or first["name"] != FREE_FEEDS_SERVICE:
                problems.append("free feed %s (%s) is served by %s" % (key, path, first and first["name"]))
    public_rx = re.compile(PUBLIC_PATHS)
    for probe in ("/", "/api/proxy/stats", "/api/v1/sample/../batch/ercot-lmp"):
        if public_rx.match(probe):
            problems.append("public-free rule would expose %s" % probe)
    return problems


def read_secret(path: str) -> str:
    mode = os.stat(path).st_mode
    if mode & (stat.S_IRWXG | stat.S_IRWXO):
        print("WARNING: %s is readable by group/others; chmod 600 it" % path, file=sys.stderr)
    secret = open(path).read().strip()
    if len(secret) < 32:
        raise SystemExit("%s: gateway secret must be at least 32 characters" % path)
    return secret


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", default="aperture.base.yaml",
                    help="settings + all hourly rule definitions (never overwritten)")
    ap.add_argument("--pricing", default=os.environ.get("AURAGRID_PRICING_CONFIG", "pricing.yaml"))
    ap.add_argument("--out", default=os.environ.get("AURAGRID_APERTURE_CONFIG", "aperture.yaml"),
                    help="generated config (default: aperture.yaml)")
    ap.add_argument("--btc-usd", type=float, help="BTC/USD to use instead of the live feeds")
    ap.add_argument("--gateway-secret-file", help="inject X-AurAgrid-Gateway into paid services")
    ap.add_argument("--listenaddr", help="override listenaddr (e.g. 0.0.0.0:8080 when there is no TLS front end yet)")
    ap.add_argument("--backend", help="override every service's backend address (host:port)")
    ap.add_argument("--tls", action="store_true",
                    help="serve HTTPS with the certificate in Aperture's dir (tls.cert/tls.key, "
                         "installed by scripts/install_tls_cert.sh)")
    ap.add_argument("--check", action="store_true", help="print a diff and exit 1 if the output would change")
    args = ap.parse_args(argv)
    out = os.path.expanduser(args.out)
    if os.path.abspath(out) == os.path.abspath(args.base):
        raise SystemExit("--out must differ from --base: the base keeps the rules of feeds not sold today")

    with open(args.base) as fh:
        base = yaml.safe_load(fh) or {}
    plans = load_plans(args.pricing)
    access = load_access(args.pricing)
    btc = args.btc_usd
    if btc is None and any(p.sats is None for p in plans):
        btc = aggregate(list(fetch_all().values()))
        if btc is None:
            print("Could not get a trustworthy BTC/USD price; pass --btc-usd", file=sys.stderr)
            return 2
    secret = read_secret(args.gateway_secret_file) if args.gateway_secret_file else None

    config = build(base, plans, btc, secret, access)
    if args.listenaddr:
        config["listenaddr"] = args.listenaddr
    if args.tls:
        config["insecure"] = False
    if args.backend:
        for svc in config["services"]:
            svc["address"] = args.backend
    problems = validate(config, plans, access)
    for problem in problems:
        print("ERROR:", problem, file=sys.stderr)
    if problems:
        return 2

    text = HEADER + yaml.safe_dump(config, sort_keys=False, default_flow_style=False)
    try:
        current = open(out).read()
    except FileNotFoundError:
        current = ""
    if args.check:
        diff = list(difflib.unified_diff(current.splitlines(True), text.splitlines(True), out, out + " (generated)"))
        sys.stdout.writelines(diff)
        return 1 if diff else 0

    tmp = out + ".tmp"
    with open(tmp, "w") as fh:
        fh.write(text)
    if secret:
        os.chmod(tmp, 0o600)
    os.replace(tmp, out)
    if btc:
        print("BTC/USD %.2f" % btc)
    for plan in plans:
        svc = next(s for s in config["services"] if s["name"] == plan.name)
        print("%-16s %-8s %s  %d sats%s  token %ds" % (
            plan.name, plan.kind, svc["pathregexp"], svc["price"],
            " (fallback; USD-pegged $%.2f via pricer)" % plan.usd if plan.dynamic else " (static)",
            plan.timeout))
    print("wrote %s (%d services)%s" % (out, len(config["services"]),
                                         "; contains the gateway secret, do not commit" if secret else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
